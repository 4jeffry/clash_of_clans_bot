    def get_clan_tag(self, guild_id):
        db = get_db()
        try:
            config = db.query(ServerConfig).filter(ServerConfig.guild_id == str(guild_id)).first()
            return config.clan_tag if config else None
        finally:
            db.close()

    def _generate_war_chart(self, clan_name, opp_name, clan_stars, opp_stars, clan_dest, opp_dest):
        """Membuat visual Grafik Perbandingan Bintang & Destruksi menggunakan Matplotlib"""
        fig, ax1 = plt.subplots(figsize=(6, 2.5), dpi=150)

        categories = [f"{clan_name[:10]} (Kita)", f"{opp_name[:10]} (Lawan)"]
        stars = [clan_stars, opp_stars]
        destruct = [clan_dest, opp_dest]

        x = range(len(categories))
        width = 0.35

        color_stars = '#4CAF50'
        color_dest = '#FF9800'

        rects1 = ax1.bar([p - width/2 for p in x], stars, width, label='Bintang (⭐)', color=color_stars)
        
        ax2 = ax1.twinx()
        rects2 = ax2.bar([p + width/2 for p in x], destruct, width, label='Destruksi (%)', color=color_dest, alpha=0.7)

        ax1.set_ylabel('Bintang', color=color_stars, fontweight='bold')
        ax2.set_ylabel('Destruksi %', color=color_dest, fontweight='bold')
        ax1.set_xticks(x)
        ax1.set_xticklabels(categories, fontweight='bold')

        # Nilai di atas bar
        for rect in rects1:
            height = rect.get_height()
            ax1.annotate(f'{height}⭐', xy=(rect.get_x() + rect.get_width() / 2, height),
                        xytext=(0, 3), textcoords="offset points", ha='center', va='bottom', fontsize=8, fontweight='bold')

        for rect in rects2:
            height = rect.get_height()
            ax2.annotate(f'{height:.1f}%', xy=(rect.get_x() + rect.get_width() / 2, height),
                        xytext=(0, 3), textcoords="offset points", ha='center', va='bottom', fontsize=8, fontweight='bold')

        plt.title("METRICS PERBANDINGAN PERANG", fontsize=10, fontweight='bold', pad=10)
        fig.tight_layout()

        chart_buffer = io.BytesIO()
        plt.savefig(chart_buffer, format='png')
        plt.close(fig)
        chart_buffer.seek(0)
        return chart_buffer

    async def send_as_pdf(self, interaction: discord.Interaction, title: str, text: str, chart_buf=None):
        """Membuat & mengirim PDF profesional dengan Header, Visual Chart, dan Layout Rapi"""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            'HeaderTitle',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=16,
            leading=20,
            textColor=colors.HexColor('#1E293B'),
            spaceAfter=4
        )

        sub_style = ParagraphStyle(
            'HeaderSub',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9,
            textColor=colors.HexColor('#64748B'),
            spaceAfter=12
        )

        body_style = ParagraphStyle(
            'BodyTextCustom',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=10,
            leading=15,
            textColor=colors.HexColor('#334155'),
            spaceAfter=6
        )

        story = []

        # 1. HEADER DOKUMEN
        clean_title = title.replace('_', ' ').upper()
        story.append(Paragraph(f"IXIERA EXECUTIVE REPORT: {clean_title}", title_style))
        story.append(Paragraph("Generated by Niki CoC AI Intelligence System • ixiera.id", sub_style))
        story.append(Spacer(1, 6))

        # 2. SISIPKAN GRAFIK VISUAL (JIKA ADA)
        if chart_buf:
            img = Image(chart_buf, width=420, height=175)
            story.append(img)
            story.append(Spacer(1, 12))

        # 3. KONTEN DOKUMEN
        content_table_data = []
        for line in text.split('\n'):
            line_str = line.strip()
            if not line_str:
                continue
            safe_line = line_str.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            
            if safe_line.isupper() and len(safe_line) < 40:
                # Judul Bagian / Sub-header
                p = Paragraph(f"<b><font color='#0F172A'>{safe_line}</font></b>", body_style)
            else:
                p = Paragraph(safe_line, body_style)
            content_table_data.append([p])

        if content_table_data:
            t = Table(content_table_data, colWidths=[520])
            t.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
                ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#E2E8F0')),
                ('PADDING', (0,0), (-1,-1), 8),
                ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
            ]))
            story.append(t)

        doc.build(story)
        buffer.seek(0)

        filename = f"{title.replace(' ', '_').lower()}.pdf"
        discord_file = discord.File(fp=buffer, filename=filename)

        embed = discord.Embed(
            title=f"📊 Dokumen AI Pro: {clean_title}",
            description="Laporan analitis visual siap diunduh dalam format PDF di bawah ini.",
            color=discord.Color.gold()
        )
        embed.set_footer(text="ixiera.id — Operating System Studio | WA: https://wa.me/6285736048626")
        await interaction.followup.send(embed=embed, file=discord_file)

    async def _get_smart_war_data(self, clan_tag: str):
        try:
            war_data = await self.coc.get_current_war(clan_tag)
            if war_data and isinstance(war_data, dict) and war_data.get('state') in ['inWar', 'preparation']:
                return war_data
        except Exception:
            pass

        try:
            cwl_group = await self.coc.get_cwl_group(clan_tag)
            if cwl_group and isinstance(cwl_group, dict) and cwl_group.get('state') != 'notInWar':
                rounds = cwl_group.get('rounds', [])
                prep_war = None
                for r in reversed(rounds):
                    for w_tag in r.get('warTags', []):
                        if w_tag == '#0': continue
                        cwl_war = await self.coc.get_cwl_war(w_tag)
                        if cwl_war and isinstance(cwl_war, dict):
                            t1 = cwl_war.get('clan', {}).get('tag')
                            t2 = cwl_war.get('opponent', {}).get('tag')
                            
                            if t1 == clan_tag or t2 == clan_tag:
                                if t2 == clan_tag:
                                    cwl_war['clan'], cwl_war['opponent'] = cwl_war['opponent'], cwl_war['clan']
                                state = cwl_war.get('state')
                                if state == 'inWar':
                                    return cwl_war
                                elif state == 'preparation' and not prep_war:
                                    prep_war = cwl_war
                if prep_war:
                    return prep_war
        except Exception:
            pass
        return None

    async def _get_latest_finished_war(self, clan_tag: str):
        try:
            cwl_group = await self.coc.get_cwl_group(clan_tag)
            if cwl_group and isinstance(cwl_group, dict) and cwl_group.get('state') != 'notInWar':
                rounds = cwl_group.get('rounds', [])
                for r in reversed(rounds):
                    for w_tag in r.get('warTags', []):
                        if w_tag == '#0': continue
                        cwl_war = await self.coc.get_cwl_war(w_tag)
                        if cwl_war and isinstance(cwl_war, dict) and cwl_war.get('state') == 'warEnded':
                            t1 = cwl_war.get('clan', {}).get('tag')
                            t2 = cwl_war.get('opponent', {}).get('tag')
                            if t1 == clan_tag or t2 == clan_tag:
                                if t2 == clan_tag:
                                    cwl_war['clan'], cwl_war['opponent'] = cwl_war['opponent'], cwl_war['clan']
                                return cwl_war
        except Exception:
            pass
            
        war_logs = await self.coc.get_war_log(clan_tag)
        if war_logs and isinstance(war_logs, list) and len(war_logs) > 0:
            return war_logs[0]
        return None

