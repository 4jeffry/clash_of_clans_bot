    @app_commands.command(name="war-strategy", description="[AI PRO] Taktik agregat rotasi attack CWL/War (Cetak PDF + Grafik)")
    async def ai_war_strategy(self, interaction: discord.Interaction):
        await interaction.response.defer()
        clan_tag = self.get_clan_tag(interaction.guild_id)
        if not clan_tag:
            return await interaction.followup.send("❌ Server belum di-setup!")
            
        war_data = await self._get_smart_war_data(clan_tag)
        result = await run_war_strategy(str(interaction.guild_id), war_data)

        # Generate Chart Visual jika data war tersedia
        chart_buf = None
        if war_data and isinstance(war_data, dict):
            c = war_data.get('clan', {})
            o = war_data.get('opponent', {})
            chart_buf = self._generate_war_chart(
                c.get('name', 'Kita'), o.get('name', 'Lawan'),
                c.get('stars', 0), o.get('stars', 0),
                c.get('destructionPercentage', 0.0), o.get('destructionPercentage', 0.0)
            )

        await self.send_as_pdf(interaction, "Strategi_Perang_Aktif", result, chart_buf=chart_buf)

